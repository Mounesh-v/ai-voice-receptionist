import type { Doctor, DoctorSchedule, Weekday } from "@/types/doctor";

export const weekdays: Weekday[] = [
  "Monday",
  "Tuesday",
  "Wednesday",
  "Thursday",
  "Friday",
  "Saturday",
  "Sunday",
];

const weekdaySchedule: DoctorSchedule = {
  Monday: { enabled: true, start: "09:00", end: "17:00" },
  Tuesday: { enabled: true, start: "09:00", end: "17:00" },
  Wednesday: { enabled: true, start: "09:00", end: "17:00" },
  Thursday: { enabled: true, start: "09:00", end: "17:00" },
  Friday: { enabled: true, start: "09:00", end: "16:00" },
  Saturday: { enabled: false, start: "09:00", end: "13:00" },
  Sunday: { enabled: false, start: "09:00", end: "13:00" },
};

function scheduleFor(
  days: Weekday[],
  start = "09:00",
  end = "17:00",
): DoctorSchedule {
  return Object.fromEntries(
    weekdays.map((day) => [
      day,
      {
        enabled: days.includes(day),
        start,
        end: day === "Friday" && end === "17:00" ? "16:00" : end,
      },
    ]),
  ) as DoctorSchedule;
}

function doctor(
  details: Omit<Doctor, "schedule"> & { workingDays?: Weekday[] },
): Doctor {
  const { workingDays, ...profile } = details;
  return {
    ...profile,
    schedule: workingDays ? scheduleFor(workingDays) : { ...weekdaySchedule },
  };
}

